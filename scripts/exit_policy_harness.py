"""Exit-Policy Walk-Forward Harness — same-entry comparison framework.

Architectural principle: exit logic is SCANNER-SPECIFIC, not global. Output
is structured to enforce that — every verdict row keys on (scanner, symbol).

Guardrails (architect-mandated 2026-05-03):
  1. SAME-ENTRY comparison only. Each runner generates ONE signal set, then
     each policy in policies[] is evaluated against IDENTICAL entries / fees /
     slippage. No cross-policy signal-set drift permitted.
  2. Every result row includes EV LIFT vs baseline (the named baseline policy).
  3. n_oos < 20 → verdict=PARKED (not PASS). Combats the tiny-n false-hope
     pattern observed in entry-pattern W/F (positive Q4 / negative IS).
  4. Output is a flat (scanner, symbol, exit_policy, …) table — no global
     "winning exit" claim ever — only per-scanner-per-symbol verdicts.
  5. EV-realization metrics:
       mfe_capture = realized_pct_profit / max_favorable_excursion_pct
                     (averaged over WINNING trades only; range [0,1])
       mae_escape  = 1 − (realized_loss_pct / max_adverse_excursion_pct)
                     (averaged over LOSING trades only; 1.0=perfect escape)
     These tell you WHY a policy beats baseline:
       higher mfe_capture → better profit harvesting
       higher mae_escape  → better loss cutting

Quarter boundaries match wf_harness:
  Q1 2025-10-01 → 2025-12-01  IS (partial — cache starts 2025-11-05)
  Q2 2025-12-01 → 2026-02-01  IS
  Q3 2026-02-01 → 2026-03-01  OOS
  Q4 2026-03-01 → 2026-05-01  OOS

Verdict rules per (scanner × symbol × policy) cell, scored against the named
baseline cell:
  PARKED          — n_oos < 20  (insufficient OOS sample)
  KILL            — ev_lift_oos <= 0  (policy worse than or equal to baseline OOS)
  HOLD            — 0 < ev_lift_oos <= $0.10  (positive but below ship floor)
  PASS            — ev_lift_oos > $0.10  AND  ev_lift_q3 >= 0  AND  ev_lift_q4 >= 0
                    (lift must be positive on BOTH OOS halves to avoid Q4-quirks)

The baseline policy itself gets verdict=BASELINE (no lift to compare).
"""
