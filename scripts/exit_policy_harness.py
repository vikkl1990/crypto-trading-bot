def quarter_of(ts: pd.Timestamp) -> Optional[str]:
    if ts.tzinfo is None:
        ts = ts.tz_localize("UTC")
    for q, (s, e) in QUARTERS.items():
        if pd.Timestamp(s, tz="UTC") <= ts < pd.Timestamp(e, tz="UTC"):
            return q
    return None


def load_candles(symbol: str, tf: str) -> pd.DataFrame:
    p = CACHE_DIR / f"{symbol}_USDT_{tf}.parquet"
    if not p.exists():
        raise FileNotFoundError(f"missing cache: {p}")
    df = pd.read_parquet(p)
    if df.index.tz is None:
        df.index = df.index.tz_localize("UTC")
    return df.sort_index()


def add_atr(df: pd.DataFrame, period: int = 14) -> pd.Series:
    h = df["high"].astype(float); l = df["low"].astype(float)
    c = df["close"].astype(float).shift(1)
    tr = pd.concat([(h - l).abs(), (h - c).abs(), (l - c).abs()], axis=1).max(axis=1)
    return tr.rolling(period, min_periods=period).mean()


def compute_mfe_mae(
    df: pd.DataFrame,
    entry_idx: int,
    side: str,
    entry_price: float,
    eval_window_bars: int,
) -> Tuple[float, float]:
    """MFE/MAE in pct over a fixed look-forward window (policy-AGNOSTIC).
    The window is the same across all policies so MFE/MAE is a property of
    the SIGNAL, not the policy."""
    end_idx = min(entry_idx + eval_window_bars, len(df) - 1)
    if end_idx <= entry_idx:
        return 0.0, 0.0
    highs = df["high"].astype(float).values[entry_idx + 1: end_idx + 1]
    lows = df["low"].astype(float).values[entry_idx + 1: end_idx + 1]
    if side == "long":
        max_fav_price = float(np.max(highs)) if len(highs) else entry_price
        max_adv_price = float(np.min(lows)) if len(lows) else entry_price
        mfe = (max_fav_price - entry_price) / entry_price
        mae = (max_adv_price - entry_price) / entry_price   # negative
    else:
        max_fav_price = float(np.min(lows)) if len(lows) else entry_price
        max_adv_price = float(np.max(highs)) if len(highs) else entry_price
        mfe = (entry_price - max_fav_price) / entry_price
        mae = (entry_price - max_adv_price) / entry_price   # negative
    return float(mfe), float(mae)


def fee_for_trade(symbol: str, notional: float, holding_sec: int) -> float:
    """Variant C: maker entry + scalper-eligible exit (per Patch 5.18 fee model)."""
    entry_fee = notional * FEE_MAKER_PCT
    window = SCALPER_WINDOW_BTC_ETH_SEC if symbol in ("BTC", "ETH") else SCALPER_WINDOW_OTHER_SEC
    exit_fee = 0.0 if holding_sec <= window else notional * FEE_TAKER_PCT
    return entry_fee + exit_fee


# ──────────────────────────────────────────────────────────────────────
# Aggregation
# ──────────────────────────────────────────────────────────────────────
# Cell stats are returned as plain dicts (see aggregate_cell()) — no dataclass
# (Python identifiers can't contain '$', and dicts give us the cleanest schema.)


def _cumulative_drawdown(nets_in_order: List[float]) -> float:
    """Max drawdown in $ from running equity curve."""
    peak = 0.0
    eq = 0.0
    max_dd = 0.0
    for n in nets_in_order:
        eq += n
        peak = max(peak, eq)
        dd = peak - eq
        max_dd = max(max_dd, dd)
    return max_dd


def aggregate_cell(trades: List[TradeResult]) -> Dict[str, Any]:
    """Per-cell aggregate. trades must be sorted by entry_ts for max_dd."""
    if not trades:
        return {
            "n": 0, "n_is": 0, "n_oos": 0, "n_q1": 0, "n_q2": 0, "n_q3": 0, "n_q4": 0,
            "ev_is_$": 0.0, "ev_oos_$": 0.0, "ev_q3_$": 0.0, "ev_q4_$": 0.0, "ev_all_$": 0.0,
            "wr_is": 0.0, "wr_oos": 0.0,
            "avg_hold_sec_is": 0.0, "avg_hold_sec_oos": 0.0,
            "max_dd_is_$": 0.0, "max_dd_oos_$": 0.0,
            "mfe_capture_oos": 0.0, "mae_escape_oos": 0.0,
        }
    by_q: Dict[str, List[TradeResult]] = {q: [] for q in QUARTERS}
    for t in trades:
        q = quarter_of(t.entry_ts)
        if q is not None:
            by_q[q].append(t)
    is_trades = by_q["Q1"] + by_q["Q2"]
    oos_trades = by_q["Q3"] + by_q["Q4"]

    def _agg(buf: List[TradeResult]) -> Dict[str, float]:
        if not buf:
            return {"n": 0, "ev_$": 0.0, "wr": 0.0, "avg_hold_sec": 0.0,
                    "max_dd_$": 0.0, "mfe_capture": 0.0, "mae_escape": 0.0}
        nets = [t.net_usd for t in buf]
        ev = float(np.mean(nets))
        wins = [t for t in buf if t.net_usd > 0]
        losses = [t for t in buf if t.net_usd <= 0]
        wr = len(wins) / len(buf)
        avg_hold = float(np.mean([t.holding_sec for t in buf]))
        # Order-stable cumulative drawdown
        nets_sorted = [t.net_usd for t in sorted(buf, key=lambda x: x.entry_ts)]
        max_dd = _cumulative_drawdown(nets_sorted)
        # MFE capture (only meaningful for winners)
        caps = []
        for t in wins:
            if t.mfe_pct > 1e-9:
                # realized_pct on winner is positive; clamp to [0, 1]
                cap = max(0.0, min(1.0, t.gross_pct / t.mfe_pct))
                caps.append(cap)
        mfe_cap = float(np.mean(caps)) if caps else 0.0
        # MAE escape (only meaningful for losers)
        escs = []
        for t in losses:
            mae_abs = abs(t.mae_pct)
            if mae_abs > 1e-9:
                lost_abs = abs(t.gross_pct)
                esc = max(0.0, min(1.0, 1.0 - lost_abs / mae_abs))
                escs.append(esc)
        mae_esc = float(np.mean(escs)) if escs else 0.0
        return {
            "n": len(buf), "ev_$": ev, "wr": wr,
            "avg_hold_sec": avg_hold, "max_dd_$": max_dd,
            "mfe_capture": mfe_cap, "mae_escape": mae_esc,
        }

    is_s = _agg(is_trades)
    oos_s = _agg(oos_trades)
    q3_s = _agg(by_q["Q3"])
    q4_s = _agg(by_q["Q4"])
    all_s = _agg(trades)

    return {
        "n": len(trades),
        "n_q1": len(by_q["Q1"]), "n_q2": len(by_q["Q2"]),
        "n_q3": len(by_q["Q3"]), "n_q4": len(by_q["Q4"]),
        "n_is": is_s["n"], "n_oos": oos_s["n"],
        "ev_is_$": is_s["ev_$"], "ev_oos_$": oos_s["ev_$"],
        "ev_q3_$": q3_s["ev_$"], "ev_q4_$": q4_s["ev_$"], "ev_all_$": all_s["ev_$"],
        "wr_is": is_s["wr"], "wr_oos": oos_s["wr"],
        "avg_hold_sec_is": is_s["avg_hold_sec"], "avg_hold_sec_oos": oos_s["avg_hold_sec"],
        "max_dd_is_$": is_s["max_dd_$"], "max_dd_oos_$": oos_s["max_dd_$"],
        "mfe_capture_oos": oos_s["mfe_capture"], "mae_escape_oos": oos_s["mae_escape"],
    }


# ──────────────────────────────────────────────────────────────────────
# Verdict — vs baseline
# ──────────────────────────────────────────────────────────────────────
def verdict_vs_baseline(
    cell: Dict[str, Any],
    baseline: Dict[str, Any],
    is_baseline: bool,
) -> Dict[str, Any]:
    if is_baseline:
        return {
            "verdict": "BASELINE",
            "ev_lift_oos_$": 0.0, "ev_lift_is_$": 0.0,
            "ev_lift_q3_$": 0.0, "ev_lift_q4_$": 0.0,
            "wr_delta_oos": 0.0,
            "avg_hold_delta_sec_oos": 0.0,
            "max_dd_delta_oos_$": 0.0,
        }
    if cell["n_oos"] < N_OOS_PARK:
        v = "PARKED"
    else:
        ev_lift_oos = cell["ev_oos_$"] - baseline["ev_oos_$"]
        ev_lift_q3 = cell["ev_q3_$"] - baseline["ev_q3_$"]
        ev_lift_q4 = cell["ev_q4_$"] - baseline["ev_q4_$"]
        if ev_lift_oos > EV_LIFT_PASS_FLOOR and ev_lift_q3 >= 0 and ev_lift_q4 >= 0:
            v = "PASS"
        elif ev_lift_oos > EV_LIFT_HOLD_FLOOR:
            v = "HOLD"
        else:
            v = "KILL"
    return {
        "verdict": v,
        "ev_lift_oos_$": cell["ev_oos_$"] - baseline["ev_oos_$"],
        "ev_lift_is_$":  cell["ev_is_$"]  - baseline["ev_is_$"],
        "ev_lift_q3_$":  cell["ev_q3_$"]  - baseline["ev_q3_$"],
        "ev_lift_q4_$":  cell["ev_q4_$"]  - baseline["ev_q4_$"],
        "wr_delta_oos":  cell["wr_oos"]   - baseline["wr_oos"],
        "avg_hold_delta_sec_oos": cell["avg_hold_sec_oos"] - baseline["avg_hold_sec_oos"],
        "max_dd_delta_oos_$":     cell["max_dd_oos_$"]    - baseline["max_dd_oos_$"],
    }


# ──────────────────────────────────────────────────────────────────────
# Runner
# ──────────────────────────────────────────────────────────────────────
def evaluate_signal_through_policies(
    df: pd.DataFrame,
    sig: Signal,
    policies: List[ExitPolicy],
    scanner: str,
    tf_min: int,
    eval_window_bars: int,
    notional: float = NOTIONAL_DEFAULT,
) -> List[TradeResult]:
    """Run ONE signal through ALL policies. Same entry, same eval window,
    same fees — only exit logic varies. Returns one TradeResult per policy."""
    out: List[TradeResult] = []
    # Compute MFE/MAE ONCE per signal — it's policy-agnostic (signal property)
    mfe, mae = compute_mfe_mae(df, sig.entry_idx, sig.side, sig.entry_price, eval_window_bars)
    for p in policies:
        try:
            outc = p.evaluate(df, sig, tf_min, eval_window_bars)
        except Exception as e:
            # Skip this policy for this signal — don't taint the cell
            continue
        gross_pct = outc.realized_pct
        gross_usd = gross_pct * notional
        fee = fee_for_trade(sig.symbol, notional, outc.holding_sec)
        net = gross_usd - fee
        # Use signal-level mfe/mae (not the policy's window — same across policies)
        out.append(TradeResult(
            scanner=scanner, symbol=sig.symbol, policy=p.name,
            entry_ts=sig.entry_ts, side=sig.side,
            entry_price=sig.entry_price, exit_price=outc.exit_price,
            exit_reason=outc.exit_reason,
            holding_sec=outc.holding_sec, holding_bars=outc.holding_bars,
            notional_usd=notional, gross_pct=gross_pct, gross_usd=gross_usd,
            fee_usd=fee, net_usd=net, mfe_pct=mfe, mae_pct=mae,
            extra=dict(sig.extra),
        ))
    return out


def run_exit_wf(
    *,
    scanner: str,
    symbols: List[str],
    tf: str,
    tf_min: int,
    signal_generator: Callable[[pd.DataFrame, str], List[Signal]],
    policies: List[ExitPolicy],
    out_dir: Path,
    eval_window_bars: int = 60,    # 60 × 5m = 5 hours; covers any policy max_hold
    notional: float = NOTIONAL_DEFAULT,
    extra_notes: Optional[List[str]] = None,
) -> Dict[str, Any]:
    """Main runner. Generates signals once per symbol, evaluates all policies."""
    out_dir.mkdir(parents=True, exist_ok=True)
    assert sum(1 for p in policies if p.is_baseline) == 1, \
        "exactly one policy must be marked is_baseline=True"
    baseline_name = next(p.name for p in policies if p.is_baseline)

    t0 = _time.time()
    cells: Dict[Tuple[str, str], Dict[str, Any]] = {}    # (symbol, policy) → cell stats
    all_trades: List[TradeResult] = []
    n_signals_per_sym: Dict[str, int] = {}

    for sym in symbols:
        try:
            df = load_candles(sym, tf)
        except FileNotFoundError as e:
            print(f"[{scanner}|{sym}] SKIP — {e}")
            continue
        df.attrs["symbol"] = sym
        sigs = signal_generator(df, sym)
        n_signals_per_sym[sym] = len(sigs)
        print(f"[{scanner}|{sym}] {len(sigs)} signals generated")

        # Group trades by policy for this symbol
        trades_by_policy: Dict[str, List[TradeResult]] = {p.name: [] for p in policies}
        for s in sigs:
            policy_trades = evaluate_signal_through_policies(
                df, s, policies, scanner, tf_min, eval_window_bars, notional,
            )
            for tr in policy_trades:
                trades_by_policy[tr.policy].append(tr)
                all_trades.append(tr)
        for pname, trs in trades_by_policy.items():
            cells[(sym, pname)] = aggregate_cell(trs)

    # Build output rows: (scanner × symbol × policy) with verdict-vs-baseline
    rows: List[Dict[str, Any]] = []
    for sym in symbols:
        if (sym, baseline_name) not in cells:
            continue
        baseline_stats = cells[(sym, baseline_name)]
        for p in policies:
            cs = cells.get((sym, p.name))
            if cs is None:
                continue
            v = verdict_vs_baseline(cs, baseline_stats, p.is_baseline)
            row = {
                "scanner": scanner, "symbol": sym, "policy": p.name,
                "is_baseline": p.is_baseline,
                **cs, **v,
            }
            rows.append(row)

    wall = round(_time.time() - t0, 1)
    summary = {
        "scanner": scanner,
        "symbols": symbols,
        "tf": tf,
        "policies": [p.name for p in policies],
        "baseline_policy": baseline_name,
        "eval_window_bars": eval_window_bars,
        "notional": notional,
        "n_signals_per_sym": n_signals_per_sym,
        "n_trade_records": len(all_trades),
        "wall_sec": wall,
        "started_at": datetime.now(timezone.utc).isoformat(),
        "rows": rows,
    }

    (out_dir / "exit_walkforward.json").write_text(
        json.dumps(summary, indent=2, default=str)
    )

    # Markdown report
    md = [
        f"# {scanner} — Exit-Policy Walk-Forward Report",
        "",
        f"Generated: {summary['started_at']}",
        f"Wall: {wall}s   Symbols: {', '.join(symbols)}   TF: {tf}   "
        f"Eval window: {eval_window_bars} bars",
        f"Baseline policy: **{baseline_name}**",
        f"n trade records: {len(all_trades)}    "
        f"signals/sym: " + ", ".join(f"{k}={v}" for k, v in n_signals_per_sym.items()),
        "",
        "## Architect-mandated guardrails",
        "- Same entries / same fees / same slippage across all policies (only exit differs)",
        "- n_oos < 20 → **PARKED** (not PASS)",
        "- PASS requires ev_lift_oos > $0.10 AND ev_lift_q3 ≥ 0 AND ev_lift_q4 ≥ 0",
        "- Output is per (scanner × symbol × policy) — never a global winner",
        "",
    ]
    if extra_notes:
        md += ["## Notes", *extra_notes, ""]

    md += ["## Per-(scanner × symbol × policy) verdicts",
           "",
           "| scanner | symbol | policy | n_is | n_oos | base_ev | pol_ev | EV lift | wr Δ | hold_Δ_min | max_dd_Δ | mfe_cap | mae_esc | verdict |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        hold_delta_min = r["avg_hold_delta_sec_oos"] / 60.0
        # find baseline EV for that (scanner,symbol)
        bsl = next((rr for rr in rows if rr["symbol"] == r["symbol"] and rr["is_baseline"]), None)
        base_ev = bsl["ev_oos_$"] if bsl else 0.0
        md.append(
            f"| {r['scanner']} | {r['symbol']} | {r['policy']} | "
            f"{r['n_is']} | {r['n_oos']} | "
            f"${base_ev:+.3f} | ${r['ev_oos_$']:+.3f} | "
            f"${r['ev_lift_oos_$']:+.3f} | {r['wr_delta_oos']*100:+.1f}pp | "
            f"{hold_delta_min:+.1f} | ${r['max_dd_delta_oos_$']:+.2f} | "
            f"{r['mfe_capture_oos']*100:.0f}% | {r['mae_escape_oos']*100:.0f}% | "
            f"**{r['verdict']}** |"
        )

    # Per-symbol "winning policy" highlight (NOT a global winner — per symbol only)
    md += ["", "## Per-symbol winner (only among PASS / HOLD; PARKED skipped)", ""]
    for sym in symbols:
        sym_rows = [r for r in rows if r["symbol"] == sym and not r["is_baseline"]
                    and r["verdict"] in ("PASS", "HOLD")]
        if not sym_rows:
            md.append(f"- **{sym}**: no policy beats baseline (or all PARKED)")
            continue
        best = max(sym_rows, key=lambda r: r["ev_lift_oos_$"])
        md.append(
            f"- **{sym}**: `{best['policy']}` (verdict {best['verdict']}, "
            f"EV lift OOS = ${best['ev_lift_oos_$']:+.3f}/trade, n_oos={best['n_oos']})"
        )

    md += ["", "## Verdict count", "", "| Verdict | Count |", "|---|---|"]
    vc: Dict[str, int] = {}
    for r in rows:
        vc[r["verdict"]] = vc.get(r["verdict"], 0) + 1
    for v, n in sorted(vc.items(), key=lambda x: -x[1]):
        md.append(f"| {v} | {n} |")

    (out_dir / "report.md").write_text("\n".join(md) + "\n")
    print(f"=== {scanner} DONE ({wall}s)  rows={len(rows)} ===")
    return summary
