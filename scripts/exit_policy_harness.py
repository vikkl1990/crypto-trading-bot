# ──────────────────────────────────────────────────────────────────────
# Data structures
# ──────────────────────────────────────────────────────────────────────
@dataclass
class Signal:
    """A single entry decision — generated by a scanner detector once,
    then evaluated against multiple exit policies."""
    symbol: str
    entry_idx: int
    entry_ts: pd.Timestamp
    side: str                       # 'long' | 'short'
    entry_price: float
    sweep_extreme: float            # for SL anchoring (low for LONG sweep, high for SHORT)
    atr_at_entry: float
    extra: Dict[str, Any] = field(default_factory=dict)


@dataclass
class ExitOutcome:
    exit_idx: int
    exit_ts: pd.Timestamp
    exit_price: float
    exit_reason: str
    holding_bars: int
    holding_sec: int
    mfe_pct: float                  # max favorable excursion over the eval window
    mae_pct: float                  # max adverse excursion over the eval window
    realized_pct: float             # signed: + for profit, - for loss


@dataclass
class TradeResult:
    """Combined per-(signal × policy) record."""
    scanner: str
    symbol: str
    policy: str
    entry_ts: pd.Timestamp
    side: str
    entry_price: float
    exit_price: float
    exit_reason: str
    holding_sec: int
    holding_bars: int
    notional_usd: float
    gross_pct: float                # = realized_pct
    gross_usd: float
    fee_usd: float
    net_usd: float
    mfe_pct: float
    mae_pct: float
    extra: Dict[str, Any] = field(default_factory=dict)


class ExitPolicy(ABC):
    """Pluggable exit policy. Same-entry guarantee: every policy receives
    identical Signal + identical df slice; only their evaluate() differs."""
    name: str = "abstract"
    is_baseline: bool = False        # exactly ONE policy per runner is baseline

    @abstractmethod
    def evaluate(
        self,
        df: pd.DataFrame,
        sig: Signal,
        tf_min: int,
        eval_window_bars: int,
    ) -> ExitOutcome:
        """Must be deterministic — same inputs → same outputs. No randomness."""
        ...


